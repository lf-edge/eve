"""Regenerate pkg/fw/firmware-<arch>.txt, the firmware an architecture ships.

The list is what that architecture's kernels can load: every firmware name
their modules and built-in drivers declare (MODULE_FIRMWARE), resolved
against the files pkg/fw's build stage installs, narrowed by the rules in
pkg/fw/firmware-select.txt. Run it after changing the kernel or any firmware
version in pkg/fw:

    tools/update-fw-lists.py            # every architecture in the rules
    tools/update-fw-lists.py amd64      # one
    tools/update-fw-lists.py --check    # fail if a committed list is stale

It needs docker with buildx. Kernel images are the ones the Makefile pins
(make kernel-tag); the firmware tree is pkg/fw's "build" stage.
"""

# A script named like the other tools/*.py, not an importable module.
# pylint: disable=invalid-name

import argparse
import difflib
import fnmatch
import io
import lzma
import os
import posixpath
import re
import subprocess
import sys
import tarfile
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = os.path.join(ROOT, 'pkg', 'fw')
RULES = os.path.join(PKG, 'firmware-select.txt')
FW_PREFIX = 'lib/firmware/'
# iwlwifi declares one name per MAC and RF type, at the newest API it
# supports. At load time it takes the silicon steps and the CDB flag from the
# hardware, and walks the API down to its minimum; "-c<core>" names rank
# above the plain ones.
IWLWIFI = re.compile(r'^(iwlwifi-.+)-(c?)(\d+)\.ucode$')
GENERATED = 'Generated by tools/update-fw-lists.py from firmware-select.txt: do not edit.'
MISSING_NOTE = """\
# Declared by a module but not in the firmware tree. This is usually harmless:
# the driver also accepts another version, listed below when the tree has one
# (ath10k, iwlwifi); the declaration is stale (rsi loads rsi/<name>); or the
# file was never published to linux-firmware (Apple Broadcom parts, Realtek
# SDIO Bluetooth, chips newer than the kernel). A name that newly appears here
# after a kernel or firmware update may be a driver that lost its firmware.
"""


def run(cmd, **kw):
    """Run a command, returning its stdout as bytes."""
    return subprocess.run(cmd, check=True, stdout=subprocess.PIPE, **kw).stdout


def parse_rules(path):
    """Read firmware-select.txt into {arch: {...}}."""
    rules = {}
    with open(path, encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.split('#', 1)[0].split()
            if not line:
                continue
            arch, kind, args = line[0], line[1], line[2:]
            r = rules.setdefault(arch, {'platforms': [], 'modules': [], 'excludes': [],
                                        'extras': []})
            if kind == 'platforms':
                r['platforms'] += args
            elif kind == 'module' and len(args) in (1, 2):
                r['modules'].append((args[0], re.compile(args[1]) if len(args) == 2 else None))
            elif kind == 'exclude' and len(args) == 1:
                r['excludes'].append(re.compile(args[0]))
            elif kind == 'extra' and len(args) == 1:
                r['extras'].append(args[0])
            else:
                sys.exit(f'{path}:{n}: cannot parse')
    return rules


def kernel_tag(arch, platform):
    """The kernel image the Makefile pins for arch and platform."""
    out = run(['make', '-s', f'ZARCH={arch}', f'PLATFORM={platform}', 'kernel-tag'], cwd=ROOT)
    return out.decode().split()[-1]


def modinfo_firmware(data):
    """Firmware names in a module's .modinfo strings."""
    return {kv[9:].decode() for kv in data.split(b'\0') if kv.startswith(b'firmware=')}


def declared(arch, tag):
    """{module: set(firmware names)} for every module and built-in driver."""
    out = {}
    cid = run(['docker', 'create', '--platform', f'linux/{arch}', tag, '/none']).decode().strip()
    try:
        image = io.BytesIO(run(['docker', 'cp', f'{cid}:/kernel.tar', '-']))
    finally:
        run(['docker', 'rm', '-f', cid])
    with tarfile.open(fileobj=image) as outer, \
            tarfile.open(fileobj=outer.extractfile('kernel.tar')) as inner:
        for m in inner:
            name = m.name.lstrip('./')
            if not name.startswith('lib/modules/') or not m.isfile():
                continue
            base = posixpath.basename(name)
            if re.search(r'\.ko(\.xz)?$', base):
                data = inner.extractfile(m).read()
                if base.endswith('.xz'):
                    data = lzma.decompress(data)
                mod = re.sub(r'\.ko(\.xz)?$', '', base)
                out.setdefault(mod, set()).update(modinfo_firmware(data))
            elif base == 'modules.builtin.modinfo':
                for kv in inner.extractfile(m).read().split(b'\0'):
                    mod, sep, fw = kv.partition(b'.firmware=')
                    if sep:
                        out.setdefault(mod.decode(), set()).add(fw.decode())
    return out


def firmware_tree(arch):
    """{path: link target or None} under /lib/firmware of pkg/fw's build stage."""
    tree = {}
    with tempfile.TemporaryFile() as tmp:
        subprocess.run(['docker', 'buildx', 'build', '--quiet', '--platform', f'linux/{arch}',
                        '--build-arg', 'PLATFORM=generic', '--target', 'build',
                        '--output', 'type=tar,dest=-', PKG], check=True, stdout=tmp)
        tmp.seek(0)
        with tarfile.open(fileobj=tmp) as tar:
            for m in tar:
                name = m.name.lstrip('./')
                if name.startswith(FW_PREFIX) and (m.isfile() or m.issym()):
                    tree[name[len(FW_PREFIX):]] = m.linkname if m.issym() else None
    return tree


def add(name, tree, out):
    """Add name and everything its symlinks point to; False if it is not there."""
    while name in tree:
        if name in out:
            return True
        out.add(name)
        if tree[name] is None:
            return True
        name = posixpath.normpath(posixpath.join(posixpath.dirname(name), tree[name]))
    return False


def iwlwifi_family(prefix):
    """An iwlwifi name prefix with the steps and the CDB flag wildcarded."""
    return re.sub(r'-([a-z]+)4-\?0$', r'-\1-?0', re.sub(r'-[a-z]0(?=-|$)', '-?0', prefix))


def iwlwifi_api(m):
    """The API number of an IWLWIFI match, core numbers above plain ones."""
    return int(m.group(3)) + (1000 if m.group(2) else 0)


def expand(name, tree):
    """A declared name, or the files a declared pattern matches."""
    if not any(c in name for c in '*?['):
        return [name]
    return sorted(f for f in tree if fnmatch.fnmatchcase(f, name)) or [name]


def resolve(name, tree, out):
    """Add a declared name as the kernel would load it."""
    m = IWLWIFI.match(name)
    if not m:
        return add(name, tree, out)
    family, top = iwlwifi_family(m.group(1)), iwlwifi_api(m)
    newest = {}
    for f in tree:
        g = IWLWIFI.match(f)
        if g and iwlwifi_family(g.group(1)) == family and iwlwifi_api(g) <= top:
            newest[g.group(1)] = max(newest.get(g.group(1), (0, '')), (iwlwifi_api(g), f))
    for prefix, (_, f) in newest.items():
        add(f, tree, out)
        add(f'{prefix}.pnvm', tree, out)
    return bool(newest)


def declared_names(rule, decl):
    """The (module, declared name) pairs the module rules pick."""
    for mod, pattern in rule['modules']:
        mods = decl if mod == '*' else {mod: decl.get(mod, set())}
        for m, names in sorted(mods.items()):
            yield from ((m, n) for n in sorted(names) if not pattern or pattern.search(n))


def select(arch, rule, decl, tree):
    """The files rule selects from tree, and the declared names tree lacks."""
    out, missing = set(), set()
    for mod, name in declared_names(rule, decl):
        for f in expand(name, tree):
            if any(x.search(f) for x in rule['excludes']):
                continue
            if not resolve(f, tree, out):
                missing.add((mod, f))
    for glob in rule['extras']:
        hits = [f for f in tree if fnmatch.fnmatchcase(f, glob)]
        if not hits:
            sys.exit(f'{arch}: extra {glob} matches nothing in the firmware tree')
        for f in hits:
            add(f, tree, out)
    return out, missing


def generate(arch, rule):
    """The contents of pkg/fw/firmware-<arch>.txt."""
    tags = [kernel_tag(arch, p) for p in rule['platforms']]
    decl = {}
    for tag in tags:
        print(f'{arch}: reading {tag}', file=sys.stderr)
        for mod, names in declared(arch, tag).items():
            decl.setdefault(mod, set()).update(names)
    print(f'{arch}: building pkg/fw build stage', file=sys.stderr)
    out, missing = select(arch, rule, decl, firmware_tree(arch))
    print(f'{arch}: {len(out)} files; '
          f'{len(missing)} declared names are not in the firmware tree', file=sys.stderr)
    return ''.join([f'# {GENERATED}\n',
                    *(f'# kernel: {tag}\n' for tag in tags),
                    MISSING_NOTE,
                    *(f'# missing: {mod} {name}\n' for mod, name in sorted(missing)),
                    *(f'{name}\n' for name in sorted(out))])


def main():
    """Entry point."""
    ap = argparse.ArgumentParser(description=__doc__.split('\n', 1)[0])
    ap.add_argument('arch', nargs='*', help='architectures to regenerate (default: all)')
    ap.add_argument('--check', action='store_true',
                    help='write nothing; show the difference and fail if a list is stale')
    args = ap.parse_args()
    rules = parse_rules(RULES)
    stale = []
    for arch in args.arch or sorted(rules):
        if arch not in rules:
            sys.exit(f'no rules for {arch} in {RULES}')
        text = generate(arch, rules[arch])
        path = os.path.join(PKG, f'firmware-{arch}.txt')
        rel = os.path.relpath(path, ROOT)
        if not args.check:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
            continue
        try:
            with open(path, encoding='utf-8') as f:
                old = f.read()
        except FileNotFoundError:
            old = ''
        if old != text:
            sys.stdout.writelines(difflib.unified_diff(
                old.splitlines(True), text.splitlines(True), rel, f'{rel} (generated)'))
            stale.append(rel)
    if stale:
        sys.exit(f'{", ".join(stale)} out of date: '
                 'run tools/update-fw-lists.py and commit the result')


if __name__ == '__main__':
    main()
