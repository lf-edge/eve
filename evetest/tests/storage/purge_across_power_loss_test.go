const (
	powerCutMethodParamKey = "POWER_CUT_METHOD"
	appDiskSizeMiBParamKey = "APP_DISK_SIZE_MB"

	// EVE version the test runs unless EVETEST_EVE_VERSION overrides it.
	purgeTestEVEVersion = "17.0.0-lts"

	// powerCutPowerCycle takes the node down by pulling its (virtual) power,
	// so EVE has no opportunity to shut anything down.
	powerCutPowerCycle = "power-cycle"
	// powerCutControllerReboot takes the node down with a reboot command from
	// the controller. EVE stops parsing the rest of the configuration as soon
	// as it sees a new reboot counter, so a purge submitted afterwards is only
	// acted upon on the next boot -- the same ordering a power cut produces.
	powerCutControllerReboot = "controller-reboot"

	// How long the app may take to start when its image still has to be
	// downloaded into a fresh volume.
	purgeTestAppStartTimeout = 15 * time.Minute
	// The same, on the first boot of an EVE-k node, where volumemgr blocks up to
	// 20 minutes waiting for Kubernetes and Longhorn and another 20 minutes for
	// cluster storage to be able to serve a volume, before it publishes
	// anything. On a node that has never held a volume the second wait cannot
	// succeed: Longhorn refuses to create its disk until /persist/vault/volumes
	// exists, and that directory is created by volumemgr's initializeDirs only
	// after the wait gives up. A budget below the wait is indistinguishable from
	// a node that is genuinely stuck.
	purgeTestAppStartTimeoutKube = 50 * time.Minute
	// How long EVE gets to carry out the deferred purge and bring the app back
	// after the power is restored. The EVE-k first-boot wait above does not
	// apply here: by this point the volume directory exists, so Longhorn's disk
	// is schedulable as soon as it syncs.
	purgeCompletionTimeout     = 20 * time.Minute
	purgeCompletionTimeoutKube = 30 * time.Minute
	// How long a single node needs to form its K3s cluster (EVE-k only).
	purgeTestK3sReadyTimeout = 20 * time.Minute
	// How long the node gets to come back from a reboot.
	purgeTestRebootTimeout = 5 * time.Minute
	// Interval between two device-side pubsub reads.
	purgeTestPollInterval = 10 * time.Second
	// Timeout of a single device-side read.
	purgeTestReadTimeout = time.Minute

	// Delimiter used to concatenate pubsub objects read from the device.
	pubsubObjectDelimiter = "<<<evetest-object-end>>>"
)

// TestAppPurgeAcrossPowerLoss verifies that a purge requested while the node is
// down is carried out once the node comes back, leaving the application running
// on exactly one, freshly created volume.
//
// This reproduces a field failure in which the app never recovers: zedmanager
// waits for a volume notification from volumemgr that cannot arrive, because
// volumemgr has already concluded on this boot that the volume in question is
// not wanted and therefore never created (or published a status for) it.
// Rebooting the node in that state is reported to add another purge copy of the
// volume without removing the previous one.
//
// Network model
// -------------
//   - netmodels.SingleEthWithDHCP -- a single management+app port is all this
//     test needs; the app has no network adapters of its own, which keeps the
//     failure surface limited to the volume and app-instance lifecycle.
//
// Device configuration
// --------------------
//   - One edge device, recreated from a live image of the EVE version under
//     test, with a management adapter on eth0 (DHCP).
//   - One VM application (evetest.LocalRawDiskImage) whose boot disk is a raw
//     disk image generated by the test and served by evetest's own image
//     server, so the test depends on no registry and no Internet access. The
//     disk carries no OS: the app reaching RUNNING means EVE started the
//     domain, which is what the volume lifecycle assertions need.
//   - On EVE-k, grub options cap the vcpus of EVE's own containers to speed up
//     cluster formation (app performance is irrelevant here).
//
// Test parameters
// ---------------
//   - EVE_VERSION -- EVE version to run (default 17.0.0-lts).
//   - HYPERVISOR -- kvm for EVE-kvm, kubevirt for EVE-k (default kvm).
//   - TPM, FILESYSTEM -- as usual.
//   - POWER_CUT_METHOD -- power-cycle (default) or controller-reboot, see the
//     constants above.
//   - APP_DISK_SIZE_MB -- size of the generated app boot disk (default 64).
//
// Phases
// ------
//  1. app-running: deploy the VM app and wait until it runs. Record the
//     identity of its volume and the copies of that volume which exist,
//     both as volumemgr status objects and as files on disk.
//  2. node-powered-off / power-restored: take the node down, submit the purge
//     while it is down (the controller accepts it; EVE cannot see it yet), and
//     bring the node back.
//  3. purge-settled: the app must report RUNNING again, the purge must have
//     actually been applied (volumemgr reports a newer volume generation and
//     zedmanager no longer has a purge in progress), and the volume must be
//     down to a single copy. A purge legitimately runs with two copies while
//     the new one is being built, so the assertion is that the copies converge
//     to one, not that two are never seen.
//  4. rebooted-after-purge: reboot the node once more and require that the
//     volume still converges on a single copy, i.e. the reboot did not leave an
//     extra purge copy behind.
//
// Failures in phases 3 and 4 are reported without aborting the test, so that a
// stuck device is described by both verdicts plus a dump of the zedmanager and
// volumemgr state that explains where the purge stopped.
func TestAppPurgeAcrossPowerLoss(test *testing.T) {
	evetestT := evetest.Init(test)
	t := NewGomegaWithT(evetestT)
	defer evetest.Close()
	log := evetest.Logger()

	// Define configurable parameters available for the test.
	evetest.DefineTestParameters(
		evetest.TestParameterDefinition{
			Key:          evetest.EVEVersionParameterKey,
			DefaultValue: purgeTestEVEVersion,
			Description: evetest.TestParameterDescription{
				Summary: "EVE version to run on the device",
				Default: purgeTestEVEVersion,
			},
		},
		evetest.HypervisorParameter(),
		evetest.TPMParameter(),
		evetest.FilesystemParameter(),
		evetest.TestParameterDefinition{
			Key:          powerCutMethodParamKey,
			DefaultValue: powerCutPowerCycle,
			Description: evetest.TestParameterDescription{
				Summary:       "How to take the node down while the purge is submitted",
				Default:       powerCutPowerCycle,
				AllowedValues: powerCutPowerCycle + "|" + powerCutControllerReboot,
			},
		},
		evetest.TestParameterDefinition{
			Key:          appDiskSizeMiBParamKey,
			DefaultValue: 64,
			Description: evetest.TestParameterDescription{
				Summary: "Size of the generated boot disk of the VM application (in MiB)",
				Default: "64",
			},
		},
	)

	// Get parameter values set for this test execution.
	eveVersion := evetest.GetEVEVersionParameterValue()
	hypervisor := evetest.GetHypervisorParameterValue()
	withTPM := evetest.GetTPMParameterValue()
	filesystem := evetest.GetFilesystemParameterValue()
	powerCutMethod := evetest.GetTestParameter[string](powerCutMethodParamKey)
	appDiskSizeMiB := evetest.GetTestParameter[int](appDiskSizeMiBParamKey)
	if powerCutMethod != powerCutPowerCycle &&
		powerCutMethod != powerCutControllerReboot {
		evetestT.Fatalf("Unsupported %s value %q (expected %s or %s)",
			powerCutMethodParamKey, powerCutMethod,
			powerCutPowerCycle, powerCutControllerReboot)
	}

	appStartTimeout := purgeTestAppStartTimeout
	purgeTimeout := purgeCompletionTimeout
	if hypervisor == evetest.HypervisorKubevirt {
		appStartTimeout = purgeTestAppStartTimeoutKube
		purgeTimeout = purgeCompletionTimeoutKube
	}

	// Set up the test harness and specify the test prerequisites.
	const devName = "edge-dev"
	requiredDevice := evetest.RequireEdgeDevice{
		Name:              devName,
		WithEVEVersion:    eveVersion,
		WithHypervisor:    hypervisor,
		WithTPM:           withTPM,
		WithFilesystem:    filesystem,
		DeviceReusePolicy: evetest.CreateFromScratchWithLiveImage,
	}
	if hypervisor == evetest.HypervisorKubevirt {
		requiredDevice.WithGrubOptions = []string{
			"set_global hv_dom0_cpu_settings \"dom0_max_vcpus=4\"",
			"set_global hv_eve_cpu_settings \"eve_max_vcpus=3\"",
			"set_global hv_ctrd_cpu_settings \"ctrd_max_vcpus=3\"",
		}
	}
	evetest.Setup(requiredDevice, evetest.RequireNetworkModel{
		NetworkModel: netmodels.SingleEthWithDHCP,
	})
	device := evetest.GetEdgeDevice(devName)
	evetest.Checkpoint("setup-done")

	// Build and apply the device configuration: management adapter only.
	// On EVE-k the app is added once the cluster is up.
	devConfig := evetest.NewEdgeDeviceConfig(devName)
	dhcpNet := devConfig.AddNetwork(evetest.DHCPNetworkConfig{
		NetworkType: evecommon.NetworkType_V4,
	})
	devConfig.AddNetworkAdapter(evetest.NetworkAdapterConfig{
		LogicalLabel:  "eth0",
		PhysicalLabel: "eth0",
		InterfaceName: "eth0",
		NetworkUUID:   dhcpNet,
		Usage:         evecommon.PhyIoMemberUsage_PhyIoUsageMgmtAndApps,
	})
	if hypervisor == evetest.HypervisorKubevirt {
		clusterUpdates, stopClusterWatch := device.WatchClusterInfo()
		defer stopClusterWatch()
		device.ApplyConfig(devConfig, true, true)
		t.Eventually(clusterUpdates, purgeTestK3sReadyTimeout).Should(Receive(
			matchers.SatisfyPredicate("K3s node is ready", k3sNodeIsReady)))
		evetest.Checkpoint("k3s-ready")
	}

	appUUID := devConfig.AddApplication(evetest.ApplicationInstanceConfig{
		DisplayName:        "purge-test-vm",
		Activate:           true,
		Image:              evetest.LocalRawDiskImage{SizeBytes: uint64(appDiskSizeMiB) * evetest.MiB},
		VirtualizationMode: eveconfig.VmMode_HVM,
		CPUs:               1,
		MemoryBytes:        512 * evetest.MiB,
	})
	device.ApplyConfig(devConfig, true, true)
	log.Infof("Submitted config with VM application UUID=%v", appUUID)
	device.WaitUntilAppIsRunning(appUUID, appStartTimeout)
	evetest.Checkpoint("app-running")

	// Learn which volume the app runs on and what the device holds for it.
	appInfo := device.GetAppInfo(appUUID)
	t.Expect(appInfo).ToNot(BeNil())
	t.Expect(appInfo.GetVolumeRefs()).To(HaveLen(1),
		"the app is expected to have exactly one volume")
	volumeUUID := appInfo.GetVolumeRefs()[0]
	baseline := readVolumeCopies(device, volumeUUID)
	log.Infof("Volume of app %s before the purge: %s", appUUID, baseline)
	t.Expect(baseline.statuses).To(HaveLen(1),
		"volumemgr is expected to report exactly one copy of the app volume "+
			"before the purge")
	baselineGeneration := volumeGeneration(baseline.statuses[0])
	// Whether counting the volume's backing files can detect anything at all is
	// established here rather than assumed: a volume of an EVE-k app is a PVC
	// with no file under the volume directories, and an on-disk count that is
	// always zero would make the duplicate-copy check unfalsifiable.
	countFiles := len(baseline.files) == 1
	if !countFiles {
		log.Warnf("Volume %s has %d backing files, expected 1: the on-disk "+
			"copy count is not a usable signal on this device and only the "+
			"volumemgr status count will be asserted", volumeUUID, len(baseline.files))
	}

	// Take the node down, submit the purge while it is down, bring it back.
	devUpdates, stopDevWatch := device.WatchDeviceInfo()
	defer stopDevWatch()
	outageStart := time.Now()
	switch powerCutMethod {
	case powerCutPowerCycle:
		device.PowerOff()
		evetest.Checkpoint("node-powered-off")
		purgeAppAndVolume(evetestT, device, appUUID, volumeUUID)
		device.PowerOn(true)
	case powerCutControllerReboot:
		device.RequestReboot(false)
		evetest.Checkpoint("node-rebooting")
		purgeAppAndVolume(evetestT, device, appUUID, volumeUUID)
		t.Eventually(devUpdates, purgeTestRebootTimeout).Should(Receive(
			matchers.SatisfyPredicate("device has rebooted",
				func(dinfo *eveinfo.ZInfoDevice) bool {
					ts := dinfo.GetLastRebootTime()
					return ts != nil && ts.AsTime().After(outageStart)
				})))
	}
	log.Infof("Node was down for %v with the purge pending", time.Since(outageStart))
	evetest.Checkpoint("power-restored")

	// On EVE-k nothing can run before the cluster is back; wait for it so that a
	// cluster which fails to come up is not reported as a purge failure.
	if hypervisor == evetest.HypervisorKubevirt && !k3sNodeIsReady(device.GetClusterInfo()) {
		clusterUpdates, stopClusterWatch := device.WatchClusterInfo()
		defer stopClusterWatch()
		t.Eventually(clusterUpdates, purgeTestK3sReadyTimeout).Should(Receive(
			matchers.SatisfyPredicate("K3s node is ready again", k3sNodeIsReady)))
		evetest.Checkpoint("k3s-ready-after-outage")
	}

	// The app must come back up, and it must come back purged.
	appState, running := waitUntilAppRuns(device, appUUID, purgeTimeout)
	if !running {
		evetestT.Errorf("App %s did not return to RUNNING within %v after the "+
			"purge submitted while the node was down (last reported state: %s)",
			appUUID, purgeTimeout, appState)
	} else {
		log.Infof("App %s is RUNNING again", appUUID)
	}
	if problem := waitUntilPurgeIsApplied(device, appUUID, volumeUUID,
		baselineGeneration, countFiles, purgeTimeout); problem != "" {
		evetestT.Errorf("Purge of app %s was not applied cleanly: %s",
			appUUID, problem)
	}
	if evetestT.Failed() {
		logDevicePurgeState(device, appUUID, volumeUUID)
	}
	evetest.Checkpoint("purge-settled")

	// Reboot once more: this must not leave an extra copy of the volume behind.
	// The reboot is issued over SSH so that this check does not depend on how
	// far a controller-driven reboot gets on a node whose app is wedged.
	copiesBeforeReboot := readVolumeCopies(device, volumeUUID)
	device.SoftReboot(true)
	evetest.Checkpoint("rebooted-after-purge")
	if problem := waitUntilPurgeIsApplied(device, appUUID, volumeUUID,
		baselineGeneration, countFiles, purgeTimeout); problem != "" {
		evetestT.Errorf("Rebooting the node after the purge did not leave a "+
			"single volume copy behind (before the reboot: %s): %s",
			copiesBeforeReboot, problem)
		logDevicePurgeState(device, appUUID, volumeUUID)
	}
	// Whether the app runs at this point says whether a reboot is enough to get
	// out of the state phase 3 left the node in; log it either way, since it
	// tells apart a node that stays broken from one that only needs a reboot.
	appState, running = waitUntilAppRuns(device, appUUID, purgeTimeout)
	if running {
		log.Infof("App %s runs again after the post-purge reboot", appUUID)
	} else {
		evetestT.Errorf("App %s is still not RUNNING %v after the post-purge "+
			"reboot (last reported state: %s)", appUUID, purgeTimeout, appState)
		logDevicePurgeState(device, appUUID, volumeUUID)
	}
}

// k3sNodeIsReady reports whether the cluster info describes a single ready node
// with healthy storage.
func k3sNodeIsReady(info *eveinfo.ZInfoKubeCluster) bool {
	const nodeReadyCond = eveinfo.KubeNodeConditionType_KUBE_NODE_CONDITION_TYPE_READY
	if info == nil || len(info.GetNodes()) != 1 {
		return false
	}
	if info.GetStorage().GetHealth() != eveinfo.ServiceStatus_SERVICE_STATUS_HEALTHY {
		return false
	}
	for _, cond := range info.GetNodes()[0].GetConditions() {
		if cond.GetType() == nodeReadyCond {
			return cond.GetSet()
		}
	}
	return false
}

// purgeAppAndVolume submits a purge of the given application to the controller
// the way a controller does it: the purge counter of the app is incremented and
// the generation counter of its volume, plus that of the app's reference to it,
// is raised to match. EVE identifies a volume by UUID and generation counter, so
// this is what makes the purge replace the volume instead of keeping the old
// content (EdgeDevice.PurgeApplication only bumps the counter).
//
// The configuration is submitted without waiting for the device to fetch it,
// which is the point of this test: the device is down at this moment.
func purgeAppAndVolume(t *evetest.T, device *evetest.EdgeDevice,
	appUUID uuid.UUID, volumeUUID string) {
	config := device.GetConfig()
	var app *eveconfig.AppInstanceConfig
	for _, a := range config.Apps {
		if a.GetUuidandversion().GetUuid() == appUUID.String() {
			app = a
			break
		}
	}
	if app == nil {
		t.Fatalf("App %q not found in the device configuration", appUUID)
	}
	purgeCounter := app.GetPurge().GetCounter() + 1
	app.Purge = &eveconfig.InstanceOpsCmd{Counter: purgeCounter}
	var refFound, volumeFound bool
	for _, volumeRef := range app.GetVolumeRefList() {
		if volumeRef.GetUuid() == volumeUUID {
			volumeRef.GenerationCount = int64(purgeCounter)
			refFound = true
		}
	}
	for _, volume := range config.Volumes {
		if volume.GetUuid() == volumeUUID {
			volume.GenerationCount = int64(purgeCounter)
			volumeFound = true
		}
	}
	// Both generation counters have to move together: EVE only considers a
	// volume to belong to an app when the two agree.
	if !refFound || !volumeFound {
		t.Fatalf("Volume %q is missing from the configuration of app %q "+
			"(reference found: %t, volume found: %t)",
			volumeUUID, appUUID, refFound, volumeFound)
	}
	device.ApplyConfig(config, false, false)
	evetest.Logger().Infof("Submitted purge %d of app %s (volume %s generation %d)",
		purgeCounter, appUUID, volumeUUID, purgeCounter)
}

// volumeCopies describes the copies of a single volume that exist on a device:
// the VolumeStatus objects published by volumemgr (one per generation of the
// volume) and the files backing them. The status objects are the primary signal;
// the files are supporting evidence which is not available everywhere, since a
// volume of an EVE-k app is a PVC rather than a file, and the vault of a ZFS
// device is mounted inside the pillar container. The caller establishes whether
// the file list is usable by checking it against a known-good state first.
type volumeCopies struct {
	statuses []pillartypes.VolumeStatus
	files    []string
}

func (c volumeCopies) String() string {
	var statuses []string
	for _, status := range c.statuses {
		statuses = append(statuses, fmt.Sprintf("%s (state %s, generation %d)",
			status.Key(), status.State, volumeGeneration(status)))
	}
	return fmt.Sprintf("%d volumemgr status object(s) [%s], %d file(s) [%s]",
		len(c.statuses), strings.Join(statuses, ", "),
		len(c.files), strings.Join(c.files, ", "))
}

// readVolumeCopies collects every copy of the given volume present on the
// device.
func readVolumeCopies(device *evetest.EdgeDevice, volumeUUID string) volumeCopies {
	var copies volumeCopies
	for _, status := range readPublications[pillartypes.VolumeStatus](
		device, "volumemgr", "VolumeStatus") {
		if status.VolumeID.String() == volumeUUID {
			copies.statuses = append(copies.statuses, status)
		}
	}
	// A volume file is named <volume UUID>#<generation> plus a format-specific
	// suffix, and lives in the encrypted or in the clear-text volume directory.
	stdout, _, err := device.RunShellScript(fmt.Sprintf(
		"find %s %s -maxdepth 1 -name '%s*' 2>/dev/null || true",
		pillartypes.VolumeEncryptedDirName, pillartypes.VolumeClearDirName,
		volumeUUID), purgeTestReadTimeout, 0)
	if err == nil {
		copies.files = strings.Fields(stdout)
	} else {
		evetest.Logger().Warnf("Failed to list the files of volume %s: %v",
			volumeUUID, err)
	}
	return copies
}

// readPublications returns all objects published by an agent on one pubsub
// topic, read with a single SSH call.
//
// evetest.ReadAllPublications copies every object with scp, and the key of a
// volume object embeds a '#' character; rather than depend on how scp treats
// that in a remote path, the objects are concatenated by the shell and split
// here.
func readPublications[T any](device *evetest.EdgeDevice,
	agent, topic string) []T {
	script := fmt.Sprintf(
		"find /run/%s/%s -maxdepth 1 -name '*.json' -exec cat {} \\; "+
			"-exec echo '%s' \\; 2>/dev/null || true",
		agent, topic, pubsubObjectDelimiter)
	stdout, _, err := device.RunShellScript(script, purgeTestReadTimeout, 0)
	if err != nil {
		evetest.Logger().Warnf("Failed to read %s published by %s: %v",
			topic, agent, err)
		return nil
	}
	var objects []T
	for _, encoded := range strings.Split(stdout, pubsubObjectDelimiter) {
		encoded = strings.TrimSpace(encoded)
		if encoded == "" {
			continue
		}
		var object T
		if err := json.Unmarshal([]byte(encoded), &object); err != nil {
			evetest.Logger().Warnf("Failed to parse %s published by %s: %v",
				topic, agent, err)
			continue
		}
		objects = append(objects, object)
	}
	return objects
}

// volumeGeneration returns the generation of a volume copy, which is what
// distinguishes the copy created by a purge from the one it replaces.
func volumeGeneration(status pillartypes.VolumeStatus) int64 {
	return status.GenerationCounter + status.LocalGenerationCounter
}

// appInstanceStatus returns the zedmanager status of the given application, or
// nil if zedmanager has not published one.
func appInstanceStatus(device *evetest.EdgeDevice,
	appUUID uuid.UUID) *pillartypes.AppInstanceStatus {
	for _, status := range readPublications[pillartypes.AppInstanceStatus](
		device, "zedmanager", "AppInstanceStatus") {
		if status.UUIDandVersion.UUID.String() == appUUID.String() {
			return &status
		}
	}
	return nil
}

// waitUntilAppRuns waits for the application to reach RUNNING and reports the
// last state seen. Unlike EdgeDevice.WaitUntilAppIsRunning it does not fail the
// test on timeout, leaving the caller free to collect evidence from a stuck
// device first.
//
// The state comes from the status zedmanager publishes on the device, not from
// the info messages the device sends to the controller: those are published on
// change, so an app that is already RUNNING sends nothing further, which a watch
// cannot tell apart from an app that never came back. Reading the device's own
// current view has no such blind spot, and after a reboot that view is rebuilt
// from scratch, so it cannot report a state left over from before the outage.
func waitUntilAppRuns(device *evetest.EdgeDevice, appUUID uuid.UUID,
	timeout time.Duration) (lastState string, running bool) {
	deadline := time.Now().Add(timeout)
	lastState = "not published"
	for {
		if status := appInstanceStatus(device, appUUID); status != nil {
			lastState = status.State.String()
			if status.State == pillartypes.RUNNING {
				return lastState, true
			}
		}
		if time.Now().After(deadline) {
			return lastState, false
		}
		time.Sleep(purgeTestPollInterval)
	}
}

// waitUntilPurgeIsApplied waits until the device state shows a completed purge:
// zedmanager has no purge in progress for the app, and the app volume is down to
// a single copy whose generation is newer than baselineGeneration. It returns an
// empty string on success, or a description of what the device still reports
// when the timeout expires.
//
// Two copies of the volume are expected while a purge is in progress -- EVE
// builds the new one while the app still runs on the old one -- hence the wait
// for convergence instead of an immediate check.
func waitUntilPurgeIsApplied(device *evetest.EdgeDevice, appUUID uuid.UUID,
	volumeUUID string, baselineGeneration int64, countFiles bool,
	timeout time.Duration) (problem string) {
	deadline := time.Now().Add(timeout)
	for {
		problem = ""
		copies := readVolumeCopies(device, volumeUUID)
		switch {
		case len(copies.statuses) != 1:
			problem = fmt.Sprintf("volume %s has %s", volumeUUID, copies)
		case volumeGeneration(copies.statuses[0]) <= baselineGeneration:
			problem = fmt.Sprintf("volume %s is still at generation %d, so the "+
				"purge has not replaced it", volumeUUID,
				volumeGeneration(copies.statuses[0]))
		case copies.statuses[0].State != pillartypes.CREATED_VOLUME:
			problem = fmt.Sprintf("volume %s is in state %s", volumeUUID,
				copies.statuses[0].State)
		case countFiles && len(copies.files) != 1:
			problem = fmt.Sprintf("volume %s has %s", volumeUUID, copies)
		}
		if problem == "" {
			if status := appInstanceStatus(device, appUUID); status == nil {
				problem = "zedmanager has not published a status for the app"
			} else if status.PurgeInprogress != pillartypes.NotInprogress {
				problem = fmt.Sprintf("zedmanager still has purge step %d in "+
					"progress for the app (app state %s)",
					status.PurgeInprogress, status.State)
			}
		}
		if problem == "" {
			// State a passing check reached rather than just returning quietly:
			// this is the evidence that the purge replaced the volume.
			evetest.Logger().Infof("Purge of app %s is applied: %s",
				appUUID, copies)
			return ""
		}
		if time.Now().After(deadline) {
			return problem
		}
		time.Sleep(purgeTestPollInterval)
	}
}

// logDevicePurgeState dumps the zedmanager and volumemgr state that explains
// where a purge stopped.
func logDevicePurgeState(device *evetest.EdgeDevice, appUUID uuid.UUID,
	volumeUUID string) {
	log := evetest.Logger()
	if status := appInstanceStatus(device, appUUID); status != nil {
		log.Warnf("zedmanager AppInstanceStatus of app %s: state=%s "+
			"purgeInprogress=%d purgeStartedAt=%s activated=%t error=%q",
			appUUID, status.State, status.PurgeInprogress,
			status.PurgeStartedAt, status.Activated, status.Error)
		for _, vrs := range status.VolumeRefStatusList {
			log.Warnf("zedmanager VolumeRefStatus of app %s: key=%s state=%s "+
				"pendingAdd=%t verifyOnly=%t error=%q",
				appUUID, vrs.Key(), vrs.State, vrs.PendingAdd, vrs.VerifyOnly,
				vrs.Error)
		}
	} else {
		log.Warnf("zedmanager published no AppInstanceStatus for app %s", appUUID)
	}
	for _, vrs := range readPublications[pillartypes.VolumeRefStatus](
		device, "volumemgr", "VolumeRefStatus") {
		if vrs.VolumeID.String() == volumeUUID {
			log.Warnf("volumemgr VolumeRefStatus: key=%s state=%s "+
				"verifyOnly=%t error=%q", vrs.Key(), vrs.State, vrs.VerifyOnly,
				vrs.Error)
		}
	}
	log.Warnf("Volume %s on the device: %s", volumeUUID,
		readVolumeCopies(device, volumeUUID))
	if appInfo := device.GetAppInfo(appUUID); appInfo != nil {
		for _, appErr := range appInfo.GetAppErr() {
			log.Warnf("App %s error reported to the controller: %s",
				appUUID, appErr.GetDescription())
		}
	}
}
