// sshKeysParamKey selects how many SSH keys TestHugeConfigItem authorizes.
const sshKeysParamKey = "SSH_KEYS"

// defaultSSHKeys is the key count at which the configuration properties
// outgrow a pubsub message with margin; see the test's description.
const defaultSSHKeys = 200

// sshKeyComment marks the keys the test generates; the last one's comment is
// what the test looks for in the value the device reports back.
const sshKeyComment = "limits-key-%03d"

// TestHugeConfigItem verifies that a configuration property with a value of
// tens of kilobytes is handled without crashing the device: the device
// reports the property back, with the value or with an error, and stays up.
//
// The configuration properties the controller sends travel as one
// ConfigItemValueMap that zedagent publishes to every agent. String
// properties take any value; debug.enable.ssh, the authorized SSH keys, is
// the one that legitimately grows, with the number of keys. Measured on the
// real types: a 37 KB value puts the map at 75 KB on the wire, over the
// 64 KiB a pubsub message may carry, so the default of 200 2048-bit RSA keys
// (a value of about 79 KB, about 120 KB on the wire) is where an unfixed
// zedagent exits with "Too large message" while publishing the map -- and
// keeps doing so after every reboot, since the device configuration is
// checkpointed and re-read.
//
// The keys are real 2048-bit RSA keys, generated by the test, behind the
// harness's own key, so SSH access to the device keeps working on a build
// that applies the value.
//
// Network model: netmodels.SingleEthWithDHCP.
//
// Device config: one DHCP management port, a 5-second metrics interval, and
// debug.enable.ssh set to the harness's key plus SSH_KEYS generated keys.
//
// Phases:
//  1. Apply the base configuration and wait until it is processed.
//  2. Set the property, apply, and wait until the device reports it back
//     carrying the last generated key or an error, with the device still
//     reporting metrics afterwards. Stop at once if the device crashes.
//
// Parameters: HYPERVISOR (shared with the suite), SSH_KEYS (default 200).
//
// Suite placement: TestLimitsSuite.
func TestHugeConfigItem(test *testing.T) {
	evetestT := evetest.Init(test)
	t := NewGomegaWithT(evetestT)
	defer evetest.Close()

	evetest.DefineTestParameters(
		evetest.HypervisorParameter(),
		evetest.TestParameterDefinition{
			Key:          sshKeysParamKey,
			DefaultValue: defaultSSHKeys,
			Description: evetest.TestParameterDescription{
				Summary: "Number of SSH keys authorized through debug.enable.ssh",
				Default: fmt.Sprint(defaultSSHKeys),
			},
		},
	)
	hypervisor := evetest.GetHypervisorParameterValue()
	numKeys := evetest.GetTestParameter[int](sshKeysParamKey)

	device := setupDevice(hypervisor, 0)
	evetest.Checkpoint("setup-done")
	log := evetest.Logger()
	devConfig, _ := applyBaseConfig(device, hypervisor)
	evetest.Checkpoint("base-config-applied")
	crash := device.WatchForCrash()
	defer crash.Stop()

	// Phase 2: the property.
	keys, err := authorizedKeys(numKeys)
	if err != nil {
		evetestT.Fatalf("Failed to generate SSH keys: %v", err)
	}
	value := strings.TrimSpace(constants.EVESSHPublickKey) + "\n" + keys
	marker := fmt.Sprintf(sshKeyComment, numKeys-1)
	log.Infof("Authorizing %d generated SSH keys, a %d-byte value", numKeys, len(value))
	props := types.NewConfigItemValueMap()
	props.SetGlobalValueString(types.SSHAuthorizedKeys, value)
	devConfig.SetConfigProperties(props)
	devUpdates, stopDevWatch := device.WatchDeviceInfo()
	defer stopDevWatch()
	device.ApplyConfig(devConfig, true, false)
	evetest.Checkpoint("property-applied")

	var latest *eveinfo.ZInfoDevice
	item := func() *eveinfo.ZInfoConfigItem {
		return latest.GetConfigItemStatus().GetConfigItems()[string(types.SSHAuthorizedKeys)]
	}
	awaitWhileAlive(t, device, crash,
		"the device reports the property with the generated keys or an error",
		10*time.Minute, func() bool {
			for drained := false; !drained; {
				select {
				case info, ok := <-devUpdates:
					drained = !ok
					if ok {
						latest = info
					}
				default:
					drained = true
				}
			}
			return strings.Contains(item().GetValue(), marker) || item().GetError() != ""
		})
	log.Infof("The device reports the property with a %d-byte value and error %q",
		len(item().GetValue()), item().GetError())
	evetest.Checkpoint("property-reported")
}

// authorizedKeys generates n RSA keys and returns them in authorized_keys
// format, one per line, each with a comment of sshKeyComment.
func authorizedKeys(n int) (string, error) {
	var b strings.Builder
	for i := range n {
		key, err := rsa.GenerateKey(rand.Reader, 2048)
		if err != nil {
			return "", err
		}
		pub, err := ssh.NewPublicKey(&key.PublicKey)
		if err != nil {
			return "", err
		}
		line := strings.TrimSpace(string(ssh.MarshalAuthorizedKey(pub)))
		fmt.Fprintf(&b, "%s %s\n", line, fmt.Sprintf(sshKeyComment, i))
	}
	return b.String(), nil
}
