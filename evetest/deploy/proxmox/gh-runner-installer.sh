# gh-runner-installer.sh - create (or destroy) a GitHub Actions self-hosted
# runner VM on a Proxmox VE host, pre-configured for use with the evetest
# framework in distributed mode against the "proxmox" device provider broker
# (see evetest-broker-proxmox-installer.sh in this same directory).
#
#   ssh root@<pve-host>
#   wget <release-url>/gh-runner-installer.sh
#   chmod +x gh-runner-installer.sh
#   ./gh-runner-installer.sh --name ci1 --gh-username <user> --gh-pat <pat> \
#       --broker-address <broker-lan-ip>
#
# Runs as root on the PVE host. Creates a single-NIC Ubuntu VM (LAN bridge
# only -- unlike the broker VM, the runner is never attached to the evetest
# SDN uplink), installs Docker/make/git, and registers it as a GitHub Actions
# self-hosted runner against "<gh-username>/eve" using a registration token
# fetched from the GitHub API. The VM is named "gh-runner-<name>" and the
# runner's Linux user is named after --gh-username.

set -eu

# ----- defaults -------------------------------------------------------------
DESTROY=false
RUNNER_NAME=""
GH_USERNAME=""
GH_PAT=""
BROKER_ADDRESS=""
# Runner label registered with GitHub. Defaults to the VM name (unique per
# runner) if left empty; pass the same --gh-label across multiple runners so
# a CI workflow can target "any free runner" via that shared label.
GH_LABEL=""
IMAGE_URL="https://cloud-images.ubuntu.com/noble/current/noble-server-cloudimg-amd64.img"
VM_MEMORY="4096"
VM_DISK="24"
VM_CORES="2"
LAN_BRIDGE="vmbr0"
LAN_MAC=""
DOCKER_USERNAME=""
DOCKER_PASSWORD=""
DOCKER_REGISTRY="https://index.docker.io/v1/"
SSH_PUBKEY=""
STORAGE="local-lvm"
# Storage holding the cached Ubuntu cloud image and the rendered cloud-init
# snippet; must be a directory-backed storage rooted at /var/lib/vz (true for
# the default 'local' storage).
IMPORT_STORAGE="local"

SNIPPETS_DIR="/var/lib/vz/snippets"

usage() {
    cat <<USAGE
Usage: gh-runner-installer.sh --name NAME --gh-username USER --gh-pat PAT \\
           --broker-address ADDR [flags]
       gh-runner-installer.sh --destroy --name NAME --gh-username USER --gh-pat PAT

Creates (or destroys) a GitHub Actions self-hosted runner VM named
"gh-runner-NAME" on this Proxmox VE host.

Required:
  --name NAME               Runner name; the VM is named gh-runner-NAME.
  --gh-username USER        GitHub username. The repository is always
                             "USER/eve"; also used as the runner VM's Linux
                             username. Used to fetch a runner registration
                             (or removal) token from the GitHub API.
  --gh-pat PAT               GitHub PAT with Read & Write Administration
                             permission on that repository.
  --broker-address ADDR     evetest broker address, written into the VM as
                             EVETEST_BROKER_ADDRESS. Not required with
                             --destroy. If omitted, auto-detected from a
                             running "evetest-broker" VM on this same host
                             (see evetest-broker-proxmox-installer.sh) --
                             fails if none is found.

  --gh-label LABEL          GitHub Actions runner label. Default: gh-runner-NAME
                             (the VM/runner name). Pass the same label on
                             multiple runners so a workflow's "runs-on" can
                             pick any free one of them.

VM shape (all optional):
  --image-url URL           Ubuntu cloud image to boot from. Default:
                             $IMAGE_URL
  --vm-memory MiB           Default: $VM_MEMORY
  --vm-disk GiB             Default: $VM_DISK
  --vm-cores N              Default: $VM_CORES
  --storage ID              VM disk storage. Default: $STORAGE
  --import-storage ID       Storage (with 'import'/'snippets' content) for
                             the cached Ubuntu image and cloud-init file.
                             Default: $IMPORT_STORAGE
  --lan-bridge NAME         The runner VM's only NIC. Default: $LAN_BRIDGE
  --lan-mac MAC             Pin its MAC address. Default: auto-generated by
                             Proxmox.
  --docker-username USER    Registry credentials applied to every docker pull
  --docker-password PASS    made inside the VM (written to the runner user's
                             ~/.docker/config.json). Must be used together.
  --docker-registry SERVER  Default: Docker Hub ($DOCKER_REGISTRY).
  --ssh-pubkey FILE         Public key injected into the runner VM's Linux
                             user, enabling passwordless (key-only) SSH login.

Other:
  --destroy     Unregister the runner from GitHub and destroy its VM.
                (Best-effort on the VM side.)
  -h, --help    Show this help.
USAGE
}

# ----- arg parsing ----------------------------------------------------------
while [ $# -gt 0 ]; do
    case "$1" in
        --name)               RUNNER_NAME="$2"; shift 2 ;;
        --gh-username)        GH_USERNAME="$2"; shift 2 ;;
        --gh-pat)             GH_PAT="$2"; shift 2 ;;
        --broker-address)     BROKER_ADDRESS="$2"; shift 2 ;;
        --gh-label)           GH_LABEL="$2"; shift 2 ;;
        --image-url)          IMAGE_URL="$2"; shift 2 ;;
        --vm-memory)          VM_MEMORY="$2"; shift 2 ;;
        --vm-disk)            VM_DISK="$2"; shift 2 ;;
        --vm-cores)           VM_CORES="$2"; shift 2 ;;
        --storage)            STORAGE="$2"; shift 2 ;;
        --import-storage)     IMPORT_STORAGE="$2"; shift 2 ;;
        --lan-bridge)         LAN_BRIDGE="$2"; shift 2 ;;
        --lan-mac)            LAN_MAC="$2"; shift 2 ;;
        --docker-username)    DOCKER_USERNAME="$2"; shift 2 ;;
        --docker-password)    DOCKER_PASSWORD="$2"; shift 2 ;;
        --docker-registry)    DOCKER_REGISTRY="$2"; shift 2 ;;
        --ssh-pubkey)         SSH_PUBKEY="$2"; shift 2 ;;
        --destroy)            DESTROY=true; shift ;;
        -h|--help)            usage; exit 0 ;;
        *) echo "error: unknown flag: $1" >&2; usage >&2; exit 2 ;;
    esac
done

die() { echo "error: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "required command not found: $1"; }
need qm; need curl; need jq

# find_ipv4_by_mac prints the IPv4 address of $1's NIC with MAC $2 (lowercase),
# as reported by the guest agent, or nothing if it isn't up yet / not found.
find_ipv4_by_mac() {   # $1=vmid $2=mac
    ifaces="$(qm guest cmd "$1" network-get-interfaces 2>/dev/null)" || return 0
    [ -n "$ifaces" ] || return 0
    printf '%s\n' "$ifaces" | awk -v mac="$2" '
        /"hardware-address"/ {
            cur=$0; sub(/.*"hardware-address" *: *"/,"",cur); sub(/".*/,"",cur); cur_mac=cur; pending=""
        }
        cur_mac==mac && /"ip-address"/ {
            ip=$0; sub(/.*"ip-address" *: *"/,"",ip); sub(/".*/,"",ip); pending=ip
        }
        cur_mac==mac && /"ip-address-type"/ {
            t=$0; sub(/.*"ip-address-type" *: *"/,"",t); sub(/".*/,"",t)
            if (t == "ipv4" && pending != "") { print pending; exit }
        }
    '
}

[ "$(id -u)" -eq 0 ] || die "must run as root on the Proxmox host"
[ -n "$RUNNER_NAME" ] || die "--name is required"
[ -n "$GH_USERNAME" ] || die "--gh-username is required"
[ -n "$GH_PAT" ] || die "--gh-pat is required"
if [ "$DESTROY" != "true" ] && [ -z "$BROKER_ADDRESS" ]; then
    # Auto-detect from the evetest-broker VM installed by
    # evetest-broker-proxmox-installer.sh on this same host, if any.
    BROKER_VMID="$(qm list 2>/dev/null | awk '$2=="evetest-broker" {print $1; exit}')"
    if [ -n "$BROKER_VMID" ]; then
        BROKER_MAC="$(qm config "$BROKER_VMID" 2>/dev/null | awk -F'[=,]' '/^net0:/{print $2}' | tr '[:upper:]' '[:lower:]')"
        BROKER_ADDRESS="$(find_ipv4_by_mac "$BROKER_VMID" "$BROKER_MAC")"
        [ -z "$BROKER_ADDRESS" ] || echo "Auto-detected broker address: $BROKER_ADDRESS (VM $BROKER_VMID, evetest-broker)"
    fi
    [ -n "$BROKER_ADDRESS" ] || die "--broker-address is required (no running 'evetest-broker' VM found on this host to auto-detect it from -- see evetest-broker-proxmox-installer.sh, or its guest agent/LAN IP isn't up yet)"
fi
if [ -n "$DOCKER_USERNAME" ] || [ -n "$DOCKER_PASSWORD" ]; then
    if ! { [ -n "$DOCKER_USERNAME" ] && [ -n "$DOCKER_PASSWORD" ]; }; then
        die "--docker-username and --docker-password must be used together"
    fi
fi

VM_NAME="gh-runner-${RUNNER_NAME}"
[ -n "$GH_LABEL" ] || GH_LABEL="$VM_NAME"
GH_REPO="${GH_USERNAME}/eve"
CLOUDINIT_VOLID="${IMPORT_STORAGE}:snippets/gh-runner-${RUNNER_NAME}-cloudinit.yaml"
CLOUDINIT_FILE="${SNIPPETS_DIR}/gh-runner-${RUNNER_NAME}-cloudinit.yaml"

# destroy_all unregisters the runner from GitHub, then stops+destroys its VM
# and removes its cloud-init snippet. Best-effort on the VM side, but aborts
# if GitHub explicitly reports the unregister call failed (rather than the
# runner simply already being gone).
destroy_all() {
    echo "Looking up runner '$VM_NAME' on ${GH_REPO}..."
    RUNNER_ID="$(curl -sf -H "Authorization: Bearer ${GH_PAT}" \
        "https://api.github.com/repos/${GH_REPO}/actions/runners" \
        | jq -r --arg name "$VM_NAME" '.runners[]? | select(.name==$name) | .id' 2>/dev/null)" || RUNNER_ID=""
    if [ -n "$RUNNER_ID" ]; then
        echo "Unregistering GitHub runner '$VM_NAME' (id: $RUNNER_ID)..."
        HTTP_STATUS="$(curl -s -o /dev/null -w '%{http_code}' -X DELETE \
            -H "Authorization: Bearer ${GH_PAT}" \
            "https://api.github.com/repos/${GH_REPO}/actions/runners/${RUNNER_ID}")"
        [ "$HTTP_STATUS" = "204" ] || die "failed to unregister runner '$VM_NAME' (HTTP $HTTP_STATUS)"
        echo "Runner unregistered."
    else
        echo "Runner '$VM_NAME' not found on GitHub (already gone or never registered)."
    fi

    VMID="$(qm list 2>/dev/null | awk -v n="$VM_NAME" '$2==n {print $1; exit}')"
    if [ -n "$VMID" ]; then
        qm stop "$VMID" >/dev/null 2>&1 || true
        qm destroy "$VMID" --purge --destroy-unreferenced-disks 1 >/dev/null 2>&1 || true
        echo "Destroyed runner VM $VMID ($VM_NAME)"
    else
        echo "No runner VM named $VM_NAME found"
    fi
    rm -f "$CLOUDINIT_FILE"
    echo "Removed cloud-init snippet ${CLOUDINIT_FILE} (if present)."
}

if [ "$DESTROY" = "true" ]; then
    destroy_all
    exit 0
fi

need pvesh; need pvesm; need wget

EXISTING_VMID="$(qm list 2>/dev/null | awk -v n="$VM_NAME" '$2==n {print $1; exit}')"
[ -z "$EXISTING_VMID" ] || die "VM '$VM_NAME' already exists (vmid $EXISTING_VMID); destroy it first with --destroy"

# ----- fetch a runner registration token ------------------------------------
echo "Generating runner registration token for ${GH_REPO}..."
GH_TOKEN="$(curl -sf -X POST -H "Authorization: Bearer ${GH_PAT}" \
    "https://api.github.com/repos/${GH_REPO}/actions/runners/registration-token" \
    | jq -r .token 2>/dev/null)" || GH_TOKEN=""
if ! { [ -n "$GH_TOKEN" ] && [ "$GH_TOKEN" != "null" ]; }; then
    die "failed to generate a runner registration token; check --gh-username/--gh-pat"
fi

# ----- enable snippets content on $IMPORT_STORAGE (holds the cloud-init file) -----
mkdir -p "$SNIPPETS_DIR"
CUR_CONTENT="$(pvesh get "/storage/${IMPORT_STORAGE}" --output-format json 2>/dev/null | sed -n 's/.*"content"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
case ",$CUR_CONTENT," in
    *,snippets,*) : ;;
    *) pvesm set "$IMPORT_STORAGE" --content "${CUR_CONTENT:+$CUR_CONTENT,}snippets" ;;
esac

# ----- render the cloud-init snippet ----------------------------------------
if [ -n "$SSH_PUBKEY" ]; then
    [ -r "$SSH_PUBKEY" ] || die "--ssh-pubkey: cannot read $SSH_PUBKEY"
    SSH_KEY_ESCAPED="$(sed 's/\\/\\\\/g; s/"/\\"/g' "$SSH_PUBKEY")"
    SSH_AUTHORIZED_KEYS_YAML="[\"${SSH_KEY_ESCAPED}\"]"
else
    SSH_AUTHORIZED_KEYS_YAML="[]"
fi

if [ -n "$DOCKER_USERNAME" ]; then
    DOCKER_AUTH_B64="$(printf '%s:%s' "$DOCKER_USERNAME" "$DOCKER_PASSWORD" | base64 | tr -d '\n')"
    DOCKER_CONFIG_JSON="{\"auths\":{\"${DOCKER_REGISTRY}\":{\"auth\":\"${DOCKER_AUTH_B64}\"}}}"
else
    DOCKER_CONFIG_JSON="{\"auths\":{}}"
fi
DOCKER_CONFIG_JSON_B64="$(printf '%s' "$DOCKER_CONFIG_JSON" | base64 | tr -d '\n')"

ARTIFACTS_DIR="/home/${GH_USERNAME}/artifacts"
# Literal "\n" (not real newlines) between entries: this string is embedded
# below inside a double-quoted YAML scalar, so cloud-init/YAML -- not this
# shell -- turns each "\n" into the real newline when it writes the file
# inside the VM.
ENV_CONTENT="EVETEST_BROKER_ADDRESS=${BROKER_ADDRESS}\nEVETEST_COLLECT_ARTIFACTS=${ARTIFACTS_DIR}\nEVETEST_SUITE_MAX_FAILURES=-1\nEVETEST_LOG_LEVEL=debug"

cat > "$CLOUDINIT_FILE" <<EOF
#cloud-config
ssh_pwauth: false

users:
  - name: ${GH_USERNAME}
    groups: [sudo]
    shell: /bin/bash
    lock_passwd: true
    sudo: 'ALL=(ALL) NOPASSWD:ALL'
    ssh_authorized_keys: ${SSH_AUTHORIZED_KEYS_YAML}

write_files:
  - path: /etc/environment
    content: "${ENV_CONTENT}\n"
    append: true
  # The GitHub runner also reads its own .env file for injected env vars.
  # Written deferred so /opt/actions-runner exists (created by runcmd).
  - path: /opt/actions-runner/.env
    content: "${ENV_CONTENT}\n"
    defer: true
  # Deferred so the runner user (and its home directory) already exists.
  - path: /home/${GH_USERNAME}/.docker/config.json
    encoding: b64
    permissions: '0600'
    owner: ${GH_USERNAME}:${GH_USERNAME}
    content: ${DOCKER_CONFIG_JSON_B64}
    defer: true

packages:
  # qemu-guest-agent lets the PVE host query the VM (e.g. its LAN IP via
  # 'qm guest cmd <vmid> network-get-interfaces'); the VM is created with agent=1.
  - qemu-guest-agent
  - git
  - make
  - jq
  # anthropics/claude-code-action installs its own Bun runtime via a .zip
  # release archive, which needs this.
  - unzip
  # The composite action's failure-analysis steps shell out to 'gh' (e.g.
  # to fetch a PR's diff) -- available directly from Ubuntu's own universe
  # repo, no custom apt source needed.
  - gh

package_update: false
package_upgrade: false

runcmd:
  # Ubuntu's unattended-upgrades timers were observed killing an in-progress
  # CI job (systemd stops the GitHub runner service while an apt upgrade it
  # triggers is applying, which the runner then reports as the job being
  # "canceled") -- disable them completely rather than just reschedule
  # around them, since a runner VM's package set shouldn't change underneath
  # a running job at all.
  - systemctl disable --now apt-daily.timer apt-daily-upgrade.timer
  - systemctl mask apt-daily.service apt-daily-upgrade.service apt-daily.timer apt-daily-upgrade.timer
  - |
    cat > /etc/apt/apt.conf.d/20auto-upgrades <<'APTCONF'
    APT::Periodic::Update-Package-Lists "0";
    APT::Periodic::Unattended-Upgrade "0";
    APTCONF
  - systemctl enable --now qemu-guest-agent.service
  - mkdir -p ${ARTIFACTS_DIR}
  - chown ${GH_USERNAME}:${GH_USERNAME} ${ARTIFACTS_DIR}
  - [sh, -c, "curl -fsSL https://get.docker.com | sh"]
  - usermod -aG docker ${GH_USERNAME}
  # Installed as ${GH_USERNAME} (its shell-script installer writes to
  # ~/.local/bin), then symlinked into /usr/local/bin -- the GitHub Actions
  # runner service doesn't source that user's ~/.bashrc, so a per-user PATH
  # entry alone wouldn't be visible to job steps the way it would in an
  # interactive shell.
  - [sudo, -u, "${GH_USERNAME}", bash, -c, "curl -fsSL https://claude.ai/install.sh | bash"]
  - ln -sf /home/${GH_USERNAME}/.local/bin/claude /usr/local/bin/claude
  - mkdir -p /opt/actions-runner
  - |
    set -e
    cd /opt/actions-runner
    RUNNER_VERSION=\$(curl -s https://api.github.com/repos/actions/runner/releases/latest \
      | jq -r .tag_name | sed 's/v//')
    curl -sLO "https://github.com/actions/runner/releases/download/v\${RUNNER_VERSION}/actions-runner-linux-x64-\${RUNNER_VERSION}.tar.gz"
    tar -xzf "actions-runner-linux-x64-\${RUNNER_VERSION}.tar.gz"
    chown -R ${GH_USERNAME}:${GH_USERNAME} /opt/actions-runner
    sudo -u ${GH_USERNAME} ./config.sh \
      --url "https://github.com/${GH_REPO}" \
      --token "${GH_TOKEN}" \
      --labels "${GH_LABEL}" \
      --name   "${VM_NAME}" \
      --unattended
    ./svc.sh install ${GH_USERNAME}
    ./svc.sh start
EOF
echo "Rendered cloud-init at ${CLOUDINIT_FILE}"

# ----- create + start the runner VM -----------------------------------------
IMG="/var/lib/vz/template/iso/gh-runner-base.img"
if [ ! -f "$IMG" ]; then
    echo "Downloading Ubuntu cloud image ..."
    mkdir -p "$(dirname "$IMG")"
    wget -q -O "$IMG" "$IMAGE_URL"
fi

VMID="$(pvesh get /cluster/nextid)"
echo "Creating runner VM ${VMID} (${VM_NAME}) ..."
# Roll back the VM created below if anything fails before it is fully up, so a
# failed/interrupted run doesn't leave a stray half-configured VM behind.
trap 'qm destroy "$VMID" --purge --destroy-unreferenced-disks 1 >/dev/null 2>&1 || true' EXIT
qm create "$VMID" \
    --name "$VM_NAME" \
    --cores "$VM_CORES" --memory "$VM_MEMORY" \
    --cpu host --machine q35 --ostype l26 --scsihw virtio-scsi-single \
    --net0 "virtio,bridge=${LAN_BRIDGE}${LAN_MAC:+,macaddr=$LAN_MAC}" \
    --serial0 socket --agent 1
qm set "$VMID" --scsi0 "${STORAGE}:0,import-from=${IMG}"
# The imported disk is exactly the base cloud image's size -- grow it to the
# requested size. Ubuntu cloud images run cloud-init's growpart/resizefs
# modules on first boot, so the guest filesystem picks it up automatically.
qm resize "$VMID" scsi0 "${VM_DISK}G"
qm set "$VMID" --ide2 "${STORAGE}:cloudinit"
qm set "$VMID" --boot "order=scsi0"
qm set "$VMID" --ipconfig0 "ip=dhcp"
qm set "$VMID" --cicustom "user=${CLOUDINIT_VOLID}"
qm start "$VMID"
trap - EXIT

# ----- wait for the runner VM's NIC to get a DHCP address -------------------
NET0_MAC="$(qm config "$VMID" 2>/dev/null | awk -F'[=,]' '/^net0:/{print $2}' | tr '[:upper:]' '[:lower:]')"
IP_WAIT_SECS=300
echo
printf 'Waiting for runner VM %s to get an IP (guest agent + DHCP; up to %ss) ' "$VMID" "$IP_WAIT_SECS"
RUNNER_IP=""
waited=0
while [ "$waited" -lt "$IP_WAIT_SECS" ]; do
    RUNNER_IP="$(find_ipv4_by_mac "$VMID" "$NET0_MAC")"
    [ -n "$RUNNER_IP" ] && break
    printf '.'
    sleep 5
    waited=$((waited + 5))
done
echo

if [ -n "$RUNNER_IP" ]; then
    cat <<EOF

Runner VM ${VMID} (${VM_NAME}) is up at ${RUNNER_IP}.
  SSH: ssh ${GH_USERNAME}@${RUNNER_IP}   (key-only; see --ssh-pubkey)

It will finish installing Docker and self-register as a GitHub Actions
runner on ${GH_REPO} shortly (name: ${VM_NAME}, label: ${GH_LABEL}).
EOF
else
    cat <<EOF

Runner VM ${VMID} (${VM_NAME}) started, but its IP wasn't available within
${IP_WAIT_SECS}s (cloud-init/Docker install may still be in progress, or the
guest agent isn't up yet). Check it once ready:
  qm guest cmd ${VMID} network-get-interfaces
EOF
fi
